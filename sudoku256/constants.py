def anchors_to_grid(anchors: Dict[Tuple[int, int], int] = None) -> List[List[int]]:
    """將錨點字典轉化為 16x16 網格 (0 = 空)"""
    if anchors is None:
        anchors = ANCHORS_92
    grid = [[0] * N for _ in range(N)]
    for (r, c), v in anchors.items():
        grid[r][c] = v
    return grid


def puzzle_dict_to_grid(puzzle: Dict[str, List[int]]) -> List[List[int]]:
    """將行字母鍵的謎盤字典轉化為 16x16 網格"""
    grid = [[0] * N for _ in range(N)]
    for i, label in enumerate(ROW_LABELS):
        if label in puzzle:
            grid[i] = list(puzzle[label])
    return grid


def grid_to_puzzle_dict(grid: List[List[int]]) -> Dict[str, List[int]]:
    """將 16x16 網格轉化為行字母鍵的謎盤字典"""
    return {ROW_LABELS[i]: list(grid[i]) for i in range(N)}


def count_anchors(grid: List[List[int]]) -> int:
    """計算網格中非零單元格數量"""
    return sum(1 for r in range(N) for c in range(N) if grid[r][c] != 0)


def box_index(r: int, c: int) -> int:
    """計算單元格 (r, c) 所屬的宮格索引 (0-15)"""
    return (r // BOX_SIZE) * BOX_SIZE + (c // BOX_SIZE)
